"""Generate Obsidian hub notes so Graph View shows the repo's real structure.

Run from the repository root:
    python views/generate_repo_graph.py

The course markdown stays plain-link and unchanged. This script only writes
views/graph/*.md: an index, one hub per area (links to every note in it), and
one hub per week (previous/next week plus that week's plan, lesson, gate,
rubric). It then reports zero-degree notes before and after, so "connected"
is a measured claim.
"""
from __future__ import annotations

import os
import re
import shutil
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / "views" / "graph"
SKIP_DIRS = {".git", ".obsidian", "recordings", "sidecar", ".venv",
             "node_modules", "__pycache__"}
WIKI = re.compile(r"\[\[([^\]|#^]+)")
MDLINK = re.compile(r"\]\(([^)#\s]+\.md)")
WEEK = re.compile(r"week[-_]?(\d{1,2})(?!\d)", re.I)


def notes(include_generated: bool) -> list[str]:
    found = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            if not name.endswith(".md"):
                continue
            rel = Path(base, name).relative_to(ROOT).as_posix()
            if rel.startswith("views/graph/") and not include_generated:
                continue
            found.append(rel)
    return sorted(found)


def links_of(rel: str, known: set[str]) -> tuple[set[str], set[str]]:
    """Return (wikilink targets, markdown-link targets) that resolve to notes."""
    text = (ROOT / rel).read_text(encoding="utf-8", errors="replace")
    wiki, plain = set(), set()
    for m in WIKI.finditer(text):
        target = m.group(1).strip()
        target = target if target.endswith(".md") else target + ".md"
        if target in known:
            wiki.add(target)
    for m in MDLINK.finditer(text):
        target = (Path(rel).parent / m.group(1)).as_posix()
        target = os.path.normpath(target).replace("\\", "/")
        if target in known:
            plain.add(target)
    return wiki, plain


def zero_degree(include_generated: bool, kinds: str) -> list[str]:
    files = notes(include_generated)
    known = set(files)
    degree = defaultdict(int)
    for rel in files:
        wiki, plain = links_of(rel, known)
        chosen = {"wiki": wiki, "all": wiki | plain}[kinds]
        for target in chosen - {rel}:
            degree[rel] += 1
            degree[target] += 1
    return [f for f in files if degree[f] == 0]


def link(rel: str) -> str:
    return f"[[{rel[:-3]}|{rel}]]"


def week_of(rel: str) -> int | None:
    m = WEEK.search(rel)
    return int(m.group(1)) if m else None


def area_of(rel: str) -> str:
    return rel.split("/")[0] if "/" in rel else "root"


def hub_name(kind: str, key: str) -> str:
    return f"views/graph/{kind}-{key}"


def write(rel: str, body: str) -> None:
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8", newline="\n")


def generate() -> None:
    if GRAPH.exists():
        shutil.rmtree(GRAPH)
    files = notes(include_generated=False)
    by_area: dict[str, list[str]] = defaultdict(list)
    by_week: dict[int, list[str]] = defaultdict(list)
    for rel in files:
        by_area[area_of(rel)].append(rel)
        wk = week_of(rel)
        if wk is not None:
            by_week[wk].append(rel)

    weeks = sorted(by_week)
    index = ["# Repository graph index\n",
             "Generated by `views/generate_repo_graph.py`. Source files are unchanged.\n",
             "## Weeks\n"]
    index += [f"- [[{hub_name('hub-week', f'{w:02d}')}|Week {w}]]" for w in weeks]
    index += ["", "## Areas\n"]
    index += [f"- [[{hub_name('hub-area', a)}|{a}]]" for a in sorted(by_area)]
    write("views/graph/index.md", "\n".join(index) + "\n")

    for area, members in by_area.items():
        body = [f"# Area: {area}\n", f"Back to [[views/graph/index|index]]. {len(members)} notes.\n"]
        body += [f"- {link(m)}" for m in members]
        write(f"{hub_name('hub-area', area)}.md", "\n".join(body) + "\n")

    for w in weeks:
        body = [f"# Week {w}\n", "Back to [[views/graph/index|index]].\n"]
        pos = weeks.index(w)
        if pos > 0:
            body.append(f"- Previous: [[{hub_name('hub-week', f'{weeks[pos-1]:02d}')}|Week {weeks[pos-1]}]]")
        if pos < len(weeks) - 1:
            body.append(f"- Next: [[{hub_name('hub-week', f'{weeks[pos+1]:02d}')}|Week {weeks[pos+1]}]]")
        grouped = defaultdict(list)
        for m in by_week[w]:
            grouped[area_of(m)].append(m)
        for area in sorted(grouped):
            body += ["", f"## {area}"] + [f"- {link(m)}" for m in grouped[area]]
        write(f"{hub_name('hub-week', f'{w:02d}')}.md", "\n".join(body) + "\n")


if __name__ == "__main__":
    before_w = zero_degree(False, "wiki")
    before_a = zero_degree(False, "all")
    total_before = len(notes(False))
    generate()
    after_w = zero_degree(True, "wiki")
    after_a = zero_degree(True, "all")
    total_after = len(notes(True))
    print(f"notes: {total_before} before, {total_after} after (incl. generated hubs)")
    print(f"zero-degree, wikilinks only : {len(before_w)} -> {len(after_w)}")
    print(f"zero-degree, wiki + md links: {len(before_a)} -> {len(after_a)}")
    for f in after_w:
        print("  still isolated:", f)
